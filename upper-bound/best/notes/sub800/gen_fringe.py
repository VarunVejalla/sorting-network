def _log10(v):
    v = abs(Fr(v))
    n, d = v.numerator, v.denominator
    e = int((n.bit_length() - d.bit_length()) * 0.30102999566398) 
    while Fr(10) ** e > v:
        e -= 1
    while Fr(10) ** (e + 1) <= v:
        e += 1
    return e


def _round_up(v, sig=20):
    v = Fr(v)
    e = _log10(v) if v != 0 else 0
    q = Fr(10) ** (sig - 1 - e)
    r = Fr(math.ceil(v * q)) / q
    assert r >= v
    return r


def _round_dn(v, sig=20):
    v = Fr(v)
    e = _log10(v) if v != 0 else 0
    q = Fr(10) ** (sig - 1 - e)
    r = Fr(math.floor(v * q)) / q
    assert r <= v
    return r


