        K0, Xn, qd, N = s['K0'], s['Xn'], s['qd'], s['N']
        T = self.f - self.g1 + 1
        assert J // self.G <= K0 and N + K0 + 1 <= T and self.D <= T
        assert E_HI * J <= Xn * T and qd * E_HI * self.D <= T
        assert 10000 * ((K0 + 1) * J ** K0 * Xn ** (K0 + 1)) <= qd ** N
        AT = self.AT
