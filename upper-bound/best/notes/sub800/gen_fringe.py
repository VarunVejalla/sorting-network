def exp_hi(x):
    from certgen import cert_up_capped
    return cert_up_capped(x)[1]


def exp_lo(x):
    from certgen import cert_lo
    return cert_lo(x)[1]


def log_lower(y):
    """rational la with exp(la) <= y (via tac_exp_le)."""
    y = Fr(y)
    lg = math.log(float(y)) if y > 0 else None
    la = round_dn(Fr(lg) - abs(Fr(lg)) / 10 ** 14 - Fr(1, 10 ** 30), 20)
    step = abs(la) / 10 ** 14 + Fr(1, 10 ** 30)
    while exp_hi(la) > y:
        la -= step
        step *= 2
    return la


def fl(x):
    return float(x)


def ind(code, n):
    pad = " " * (n - 2)
    return "".join(pad + ln + "\n" if ln.strip() else "\n" for ln in code.rstrip("\n").split("\n"))


ELT = "have h := Real.exp_one_lt_d9; norm_num at h ⊢; linarith"
