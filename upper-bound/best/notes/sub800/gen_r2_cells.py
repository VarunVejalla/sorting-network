#!/usr/bin/env python3
"""Generate lean/R2Cells.lean: the concrete round-2 cells (LEAN-PLAN W4.5) and the final
round-2 theorem `R2Cells.round2_numeric`.

Cells (p <= 1/2) and parameters come from lean_numerics_plan.py (round 2); witnesses as in
gen_r1_cells.py.   usage: python -I gen_r2_cells.py [K_MAX]
"""
import math
import os
import sys
from fractions import Fraction as Fr

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import lean_numerics_plan as P  # noqa: E402
import gen_r1_cells as G  # noqa: E402
from gen_r1_cells import L, NN, short, tac_exp_le, tac_le_exp, log_upper, tac_y_le_exp  # noqa: E402

E1 = G.E1
D = Fr(1, 105000)
M = P.M_LO
MHI = 2 ** 26
ETA = Fr(1, 1000)


def rate_witness(prefix, pa, pb, lam, al, pa_s=None):
    """witnesses for the tangent checks of rate `al` on [pa, pb]; None if they fail.
    pa_s: the Lean expression for pa (default: its literal)."""
    pa_s = pa_s or L(pa)
    cEu, Eu = tac_exp_le(prefix + "Eu", L(al), al)
    cEl, El = tac_le_exp(prefix + "El", L(al), al)
    cQ, Q = tac_le_exp(prefix + "Q", f"{L(al)} * ({pa_s} + {L(lam)})", al * (pa + lam))
    if not (1 + pa * (Eu - 1) <= Q):
        return None
    Lq = log_upper(1 + pa * (Eu - 1))
    if not (Lq + (pb - pa) * (Eu - 1) / (1 + pa * (El - 1)) <= al * (pb + lam)):
        return None
    code = cEu + cEl + cQ + tac_y_le_exp(prefix + "Lq", f"1 + {pa_s} * ({L(Eu)} - 1)", 1 + pa * (Eu - 1), Lq)
    return code, Eu, El, Q, Lq


def main():
    kmax = int(sys.argv[1]) if len(sys.argv) > 1 else None
    worst, cells, g = P.plan_round2(E1)
    assert worst is not None, "planner failed"
    assert g % 2 == 1
    gp = (g - 1) // 2
    use = cells[:kmax] if kmax else cells
    cA1, A1 = tac_exp_le("h", "1 / 1000", Fr(1, 1000))
    cB1, B1 = tac_le_exp("h", "-(1 / 1000)", Fr(-1, 1000))
    L15000 = log_upper(Fr(15000))
    G0 = MHI // g + 2
    lnG = log_upper(Fr(G0))
    out = ["import AKS.Sub800.CellLemmas2\n",
           "/-! Generated by `gen_r2_cells.py` — do not edit. Concrete round-2 cells. -/\n",
           "set_option maxHeartbeats 4000000\n",
           "namespace R2Cells\nopen Real\n"]
    out.append("theorem hA1 : Real.exp (1 / 1000) ≤ " + L(A1) + " := by\n" + cA1 + "  exact h\n")
    out.append("theorem hB1 : " + L(B1) + " ≤ Real.exp (-(1 / 1000)) := by\n" + cB1 + "  exact h\n")
    out.append("theorem hL15000 : Real.log 15000 ≤ " + L(L15000) + " := by\n"
               + tac_y_le_exp("h", "(15000 : ℝ)", Fr(15000), L15000)
               + "  exact ExpBounds.log_le _ _ (by norm_num) h\n")
    out.append(f"theorem hlnG (m : ℕ) (hm : m ≤ {MHI}) :\n"
               f"    Real.log ((Round2Num.grid m {g}).card : ℝ) ≤ {L(lnG)} := by\n"
               + tac_y_le_exp("h", f"(({G0} : ℕ) : ℝ)", Fr(G0), lnG)
               + f"  have hc : (Round2Num.grid m {g}).card ≤ {G0} := by\n"
               f"    have := Round2Num.grid_card m {g}\n"
               f"    have h2 : m / {g} ≤ {MHI} / {g} := Nat.div_le_div_right hm\n"
               f"    omega\n"
               f"  have hpos : 0 < (Round2Num.grid m {g}).card := by\n"
               f"    rw [Finset.card_pos]\n"
               f"    exact ⟨_, Finset.mem_image_of_mem _ (Finset.mem_range.2 (Nat.succ_pos _))⟩\n"
               f"  have hcR : ((Round2Num.grid m {g}).card : ℝ) ≤ (({G0} : ℕ) : ℝ) := by exact_mod_cast hc\n"
               f"  exact ExpBounds.log_le _ _ (by exact_mod_cast hpos) (le_trans hcR h)\n")
    params = []
    for idx, (pa, pb, lam0, t0, al0, be0) in enumerate(use):
        chosen = None
        for sig in (6, 8, 10, 14, None):
            if sig is None:
                lam, t, al, be = Fr(lam0), Fr(t0), Fr(al0), Fr(be0)
            else:
                lam, t, al, be = short(lam0, sig), short(t0, sig), short(al0, sig), short(be0, sig)
            if not (0 < t < al and t < be and lam * E1 <= D / 2):
                continue
            ra = rate_witness("a", pa, pb, lam, al)
            rb = rate_witness("b", 1 - pb, 1 - pa, lam, be, f"(1 - {L(pb)})")
            if ra and rb:
                chosen = (lam, t, al, be, ra, rb)
                break
        assert chosen is not None, ("rate", idx)
        lam, t, al, be, ra, rb = chosen
        params.append((pa, pb, lam, t, al, be))
        codea, Eua, Ela, Qa, Lqa = ra
        codeb, Eub, Elb, Qb, Lqb = rb
        cxa = (t - al) * Fr(1, 1000) / t
        cxb = (t - be) * Fr(1, 1000) / t
        cC1a, C1a = tac_exp_le("hC1a", f"({L(t)} - {L(al)}) * (1 / 1000 / {L(t)})", cxa)
        cC1b, C1b = tac_exp_le("hC1b", f"({L(t)} - {L(be)}) * (1 / 1000 / {L(t)})", cxb)
        assert C1a < 1 and C1b < 1
        y2 = A1 * (1 + (1 - B1) / (1 - C1a)) + A1 * (1 + (1 - B1) / (1 - C1b)) - 1
        Lq2 = log_upper(y2)
        body = [codea, codeb, cC1a, cC1b,
                tac_y_le_exp("hLq2", f"{L(A1)} * (1 + (1 - {L(B1)}) / (1 - {L(C1a)})) + "
                             f"{L(A1)} * (1 + (1 - {L(B1)}) / (1 - {L(C1b)})) - 1", y2, Lq2)]
        q = pb
        A = log_upper(1 / q)
        B = log_upper(1 / (1 - q))
        Hq = q * A + (1 - q) * B
        body.append(tac_y_le_exp("hA", f"1 / {L(q)}", 1 / q, A))
        body.append(tac_y_le_exp("hB", f"1 / (1 - {L(q)})", 1 / (1 - q), B))
        body.append(f"  have hH : ∀ p, {L(pa)} ≤ p → p ≤ {L(pb)} → binEntropy p ≤ {L(Hq)} := by\n"
                    f"    intro p h1 h2\n"
                    f"    have h := CellLemmas.binEntropy_cell_le {L(pa)} {L(pb)} p (by norm_num) (by norm_num) h1 h2\n"
                    f"    rw [if_pos (by norm_num)] at h\n"
                    f"    have hq := CellLemmas.binEntropy_le_of {L(q)} {L(A)} {L(B)} (by norm_num) (by norm_num) hA hB\n"
                    f"    have e : {L(q)} * {L(A)} + (1 - {L(q)}) * {L(B)} = {L(Hq)} := by norm_num\n"
                    f"    linarith\n")
        fin = lam * (E1 * M + gp) + (Hq + Lq2 + (lnG + L15000) / 16) / t
        assert fin <= D / 2 * M, ("budget", idx, float(fin), float(D / 2 * M))
        out.append(f"theorem cell{idx} : Round2Num.CellOK2 {L(E1)} {L(D)} {L(gp)} {L(M)} {L(ETA)} {L(lnG)} "
                   f"{L(pa)} {L(pb)} {L(lam)} {L(t)} {L(al)} {L(be)} := by")
        out.append("".join(body).rstrip("\n"))
        out.append(f"  exact CellLemmas2.cellOK2_of_bounds {L(E1)} {L(D)} {L(gp)} {L(M)} {L(ETA)} {L(lnG)} "
                   f"{L(pa)} {L(pb)} {L(lam)} {L(t)} {L(al)} {L(be)} "
                   f"{L(Eua)} {L(Ela)} {L(Qa)} {L(Lqa)} {L(Eub)} {L(Elb)} {L(Qb)} {L(Lqb)} {L(Hq)} "
                   f"{L(C1a)} {L(C1b)} {L(Lq2)} {L(A1)} {L(B1)} {L(L15000)}")
        out.append("    " + " ".join([NN] * 9))
        out.append(f"    aEu aEl {NN} aQ {NN} aLq {NN} bEu bEl {NN} bQ {NN} bLq {NN} hH hA1 hB1 "
                   f"hC1a {NN} hC1b {NN} hLq2 hL15000 {NN}\n")
    if not kmax:
        Kc = len(params)

        def table(name, vals):
            lines = [f"noncomputable def {name} : ℕ → ℝ"]
            for i, v in enumerate(vals):
                lines.append(f"  | {i} => {L(v)}")
            lines.append(f"  | _ => {L(vals[-1])}")
            return "\n".join(lines) + "\n"
        edges = [c[0] for c in params] + [params[-1][1]]
        assert edges[0] == 0 and edges[-1] == Fr(1, 2)
        out.append(table("edge", edges))
        for nm, j in (("lamf", 2), ("tf", 3), ("alf", 4), ("bef", 5)):
            out.append(table(nm, [c[j] for c in params]))
        out.append(f"theorem cells_ok : ∀ i : Fin {Kc}, Round2Num.CellOK2 {L(E1)} {L(D)} {L(gp)} {L(M)} {L(ETA)} {L(lnG)} "
                   f"(edge i) (edge (i + 1)) (lamf i) (tf i) (alf i) (bef i) := by")
        out.append("  intro ⟨i, hi⟩")
        out.append("  interval_cases i")
        for i in range(Kc):
            out.append(f"  · exact cell{i}")
        out.append("")
        out.append(f"theorem edges_mono : ∀ i, i < {Kc} → edge i ≤ edge (i + 1) := by")
        out.append("  intro i hi")
        out.append("  interval_cases i <;> norm_num [edge]\n")
        out.append(f"theorem cover : ∀ p : ℝ, 0 ≤ p → p ≤ 1 / 2 → ∃ i : Fin {Kc}, edge i ≤ p ∧ p ≤ edge (i + 1) := by")
        out.append("  intro p h0 h1")
        out.append(f"  obtain ⟨i, hi, h⟩ := CellLemmas2.cover_of_edges_top {Kc} (by norm_num) edge (1 / 2) (by norm_num [edge]) (by norm_num [edge]) edges_mono p h0 h1")
        out.append("  exact ⟨⟨i, hi⟩, h⟩\n")
        out.append("open Classical in")
        out.append("/-- **Round 2 of the walk bound, numerically closed**: for every `n ≥ 16` and every row count")
        out.append(f"`{M} ≤ m ≤ 2^26`, at most 1/1000 of the scrambles fail Property B2 with `E1 = {float(E1):.5e}`, `d = 1/105000`. -/")
        out.append(f"theorem round2_numeric {{m n : ℕ}} (hn : 16 ≤ n) (hmM : ({M} : ℝ) ≤ m) (hmHi : m ≤ {MHI}) (hm : 0 < m) :")
        out.append(f"    ((Finset.univ.filter fun σ : Chvatal.Scramble m n => ¬ Chvatal.HasCombinatorialPropertyB2 σ {L(E1)} {L(D)}).card : ℝ) ≤")
        out.append(f"      {L(ETA)} * ((Fintype.card (Chvatal.Scramble m n) : ℕ) : ℝ) :=")
        out.append(f"  Round2Num.round2_bound {L(E1)} {L(D)} {L(M)} {L(ETA)} {L(lnG)} {gp} (by norm_num) (by norm_num) (by norm_num) (by norm_num)")
        out.append("    (fun i => edge i) (fun i => edge (i + 1)) (fun i => lamf i) (fun i => tf i) (fun i => alf i) (fun i => bef i)")
        out.append(f"    cover cells_ok hn hmM hm (hlnG m hmHi)\n")
    out.append("end R2Cells\n")
    path = os.path.join(HERE, "..", "..", "AKS", "Sub800", "R2Cells.lean")
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print(f"wrote {path}: {len(use)} of {len(cells)} cells, grid g = {g}, lnG = {float(lnG):.6f}")


if __name__ == "__main__":
    main()
