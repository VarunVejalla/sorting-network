#!/usr/bin/env python3
"""Generate AKS/Sub800/R2Cells.lean: the concrete round-2 cells (LEAN-PLAN W4.5) as checked data
and the final round-2 theorem `R2Cells.round2_numeric`.

Cells (p <= 1/2) and parameters come from lean_numerics_plan.py (round 2); witnesses as in
gen_r1_cells.py.   usage: python -I gen_r2_cells.py
"""
import math
import os
import sys
from fractions import Fraction as Fr

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import lean_numerics_plan as P  # noqa: E402
import gen_r1_cells as G  # noqa: E402
from gen_r1_cells import L, short, log_upper  # noqa: E402
from certgen import Q, cert_lo, cert_up  # noqa: E402

E1 = G.E1
D = Fr(1, 105000)
M = P.M_LO
MHI = 2 ** 26
ETA = Fr(1, 1000)


def rate_cert(pa, pb, lam, al):
    """certificates for the tangent checks of rate `al` on [pa, pb]; None if they fail."""
    cEu, Eu = cert_up(al)
    cEl, El = cert_lo(al)
    cQ, Qv = cert_lo(al * (pa + lam))
    if not (1 + pa * (Eu - 1) <= Qv):
        return None
    Lq = log_upper(1 + pa * (Eu - 1))
    if not (Lq + (pb - pa) * (Eu - 1) / (1 + pa * (El - 1)) <= al * (pb + lam)):
        return None
    cLq, lo = cert_lo(Lq)
    assert lo >= 1 + pa * (Eu - 1)
    return dict(Eu=Eu, El=El, Q=Qv, Lq=Lq, cEu=cEu, cEl=cEl, cQ=cQ, cLq=cLq)


def main():
    worst, cells, g = P.plan_round2(E1)
    assert worst is not None, "planner failed"
    assert g % 2 == 1
    gp = (g - 1) // 2
    cA1, A1 = cert_up(Fr(1, 1000))
    cB1, B1 = cert_lo(Fr(-1, 1000))
    L15000 = log_upper(Fr(15000))
    cL, lo = cert_lo(L15000)
    assert lo >= 15000
    G0 = MHI // g + 2
    lnG = log_upper(Fr(G0))
    cG, lo = cert_lo(lnG)
    assert lo >= G0
    out = ["import AKS.Sub800.CellCheck2\n",
           "/-! Generated by `gen_r2_cells.py` — do not edit. Concrete round-2 cells as checked data\n"
           "(`CellCheck2`): one `decide +kernel` checks every cell and its `exp`/`log` certificates. -/\n",
           "namespace R2Cells\n"]
    out.append("noncomputable def glob : CellCheck2.Glob where\n"
               f"  E1 := {Q(E1)}\n  d := {Q(D)}\n  gp := {gp}\n  M := {Q(M)}\n  η := {Q(ETA)}\n"
               f"  lnG := {Q(lnG)}\n  A1 := {Q(A1)}\n  B1 := {Q(B1)}\n  L15000 := {Q(L15000)}\n"
               f"  cA1 := {cA1}\n  cB1 := {cB1}\n  cL := {cL}\n")
    out.append(f"theorem hlnG (m : ℕ) (hm : m ≤ {MHI}) :\n"
               f"    Real.log ((Round2Num.grid m {g}).card : ℝ) ≤ ((glob.lnG : ℚ) : ℝ) := by\n"
               f"  have h := ExpCert.logUp_sound (y := ({G0} : ℚ)) (q := glob.lnG) (c := {cG}) (by decide +kernel)\n"
               f"  have hc : (Round2Num.grid m {g}).card ≤ {G0} := by\n"
               f"    have := Round2Num.grid_card m {g}\n"
               f"    have h2 : m / {g} ≤ {MHI} / {g} := Nat.div_le_div_right hm\n"
               f"    omega\n"
               f"  have hpos : 0 < (Round2Num.grid m {g}).card := by\n"
               f"    rw [Finset.card_pos]\n"
               f"    exact ⟨_, Finset.mem_image_of_mem _ (Finset.mem_range.2 (Nat.succ_pos _))⟩\n"
               f"  have hcR : ((Round2Num.grid m {g}).card : ℝ) ≤ (({G0} : ℚ) : ℝ) := by\n"
               f"    push_cast; exact_mod_cast hc\n"
               f"  exact (Real.log_le_log (by exact_mod_cast hpos) hcR).trans h\n")
    recs = []
    for idx, (pa, pb, lam0, t0, al0, be0) in enumerate(cells):
        chosen = None
        for sig in (6, 8, 10, 14, None):
            if sig is None:
                lam, t, al, be = Fr(lam0), Fr(t0), Fr(al0), Fr(be0)
            else:
                lam, t, al, be = short(lam0, sig), short(t0, sig), short(al0, sig), short(be0, sig)
            if not (0 < t < al and t < be and lam * E1 <= D / 2):
                continue
            ra = rate_cert(pa, pb, lam, al)
            rb = rate_cert(1 - pb, 1 - pa, lam, be)
            if ra and rb:
                chosen = (lam, t, al, be, ra, rb)
                break
        assert chosen is not None, ("rate", idx)
        lam, t, al, be, ra, rb = chosen
        cxa = (t - al) * Fr(1, 1000) / t
        cxb = (t - be) * Fr(1, 1000) / t
        cC1a, C1a = cert_up(cxa)
        cC1b, C1b = cert_up(cxb)
        assert C1a < 1 and C1b < 1
        y2 = A1 * (1 + (1 - B1) / (1 - C1a)) + A1 * (1 + (1 - B1) / (1 - C1b)) - 1
        Lq2 = log_upper(y2)
        cLq2, lo = cert_lo(Lq2)
        assert lo >= y2
        q = pb
        A = log_upper(1 / q)
        B = log_upper(1 / (1 - q))
        cA, la = cert_lo(A)
        cB, lb = cert_lo(B)
        assert la >= 1 / q and lb >= 1 / (1 - q)
        Hq = q * A + (1 - q) * B
        fin = lam * (E1 * M + gp) + (Hq + Lq2 + (lnG + L15000) / 16) / t
        assert fin <= D / 2 * M, ("budget", idx, float(fin), float(D / 2 * M))
        recs.append("  { pa := " + Q(pa) + ", pb := " + Q(pb) + ", lam := " + Q(lam) + ", tt := " + Q(t)
                    + ", al := " + Q(al) + ", be := " + Q(be)
                    + ",\n    Eua := " + Q(ra["Eu"]) + ", Ela := " + Q(ra["El"]) + ", Qa := " + Q(ra["Q"])
                    + ", Lqa := " + Q(ra["Lq"])
                    + ",\n    Eub := " + Q(rb["Eu"]) + ", Elb := " + Q(rb["El"]) + ", Qb := " + Q(rb["Q"])
                    + ", Lqb := " + Q(rb["Lq"])
                    + ",\n    C1a := " + Q(C1a) + ", C1b := " + Q(C1b) + ", Lq2 := " + Q(Lq2)
                    + ", A := " + Q(A) + ", B := " + Q(B)
                    + ",\n    cEua := " + ra["cEu"] + ",\n    cEla := " + ra["cEl"] + ",\n    cQa := " + ra["cQ"]
                    + ",\n    cLqa := " + ra["cLq"]
                    + ",\n    cEub := " + rb["cEu"] + ",\n    cElb := " + rb["cEl"] + ",\n    cQb := " + rb["cQ"]
                    + ",\n    cLqb := " + rb["cLq"]
                    + ",\n    cC1a := " + cC1a + ",\n    cC1b := " + cC1b + ",\n    cLq2 := " + cLq2
                    + ",\n    cA := " + cA + ",\n    cB := " + cB + " }")
    assert cells[0][0] == 0 and cells[-1][1] == Fr(1, 2)
    out.append("set_option maxRecDepth 100000 in")
    out.append(f"/-- The {len(recs)} cells, contiguous from `0` to `1/2`. -/")
    out.append("noncomputable def cells : List CellCheck2.Cell := [\n" + ",\n".join(recs) + "]\n")
    out.append("theorem cells_checked : CellCheck2.allOK glob cells = true := by decide +kernel\n")
    out.append("open Classical in")
    out.append("/-- **Round 2 of the walk bound, numerically closed**: for every `n ≥ 16` and every row count")
    out.append(f"`{M} ≤ m ≤ 2^26`, at most 1/1000 of the scrambles fail Property B2 with `E1 = {float(E1):.5e}`, `d = 1/105000`. -/")
    out.append(f"theorem round2_numeric {{m n : ℕ}} (hn : 16 ≤ n) (hmM : ({M} : ℝ) ≤ m) (hmHi : m ≤ {MHI}) (hm : 0 < m) :")
    out.append(f"    ((Finset.univ.filter fun σ : Chvatal.Scramble m n => ¬ Chvatal.HasCombinatorialPropertyB2 σ {L(E1)} {L(D)}).card : ℝ) ≤")
    out.append(f"      {L(ETA)} * ((Fintype.card (Chvatal.Scramble m n) : ℕ) : ℝ) := by")
    out.append("  have hE1 : ((glob.E1 : ℚ) : ℝ) = " + L(E1) + " := by norm_num [glob]")
    out.append("  have hd : ((glob.d : ℚ) : ℝ) = " + L(D) + " := by norm_num [glob]")
    out.append("  have hη : ((glob.η : ℚ) : ℝ) = " + L(ETA) + " := by norm_num [glob]")
    out.append("  have hM : ((glob.M : ℚ) : ℝ) = " + L(M) + " := by norm_num [glob]")
    out.append(f"  have hg : 2 * glob.gp + 1 = {g} := by norm_num [glob]")
    out.append("  have h := CellCheck2.round2_of_cert glob cells cells_checked hn (by rw [hM]; exact hmM) hm")
    out.append("    (by rw [hg]; exact hlnG m hmHi)")
    out.append("  rwa [hE1, hd, hη] at h\n")
    out.append("end R2Cells\n")
    path = os.path.join(HERE, "..", "..", "AKS", "Sub800", "R2Cells.lean")
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print(f"wrote {path}: {len(recs)} cells, grid g = {g}, lnG = {float(lnG):.6f}")


if __name__ == "__main__":
    main()
