#!/usr/bin/env python3
"""Cross-check the (3,2,2) candidate against the explicit uniform-U flow."""
import argparse
import sys
from collections import Counter
from fractions import Fraction as F
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "slackfree"))
from explicit import build_table
from flowsim import Par


def check(max_depth: int) -> None:
    p = Par(3, 2, 2)
    total_nodes = Counter()
    for d in range(3, max_depth + 1):
        table, _, _ = build_table(p, d, "U")
        assert len(table) == p.tf(d)
        for t, step in enumerate(table):
            for i, rows in step.items():
                active = (i == 0) if t == 0 else p.active(d, i, t)
                assert active
                assert len(rows) == p.k ** i
                role = "topDesc" if t == 0 else p.role(d, i, t)
                for j, (a, up, blocks) in enumerate(rows):
                    total_nodes[(d, role)] += 1
                    a0 = p.alloc(d, i, t)
                    u0 = p.up(d, i, t, a0)
                    b0 = p.down(d, i, t)
                    assert F(a) == a0, (d, t, i, j, "alloc", a, a0)
                    assert F(up) == u0, (d, t, i, j, "up", up, u0)
                    assert sum(blocks) == F(a) - F(up)
                    if role == "botRise":
                        assert all(v == 0 for v in blocks)
                        assert F(up) == F(a)
                    else:
                        # Uniform design U sends exactly beta=down(d,i,t)
                        # wires to each child, including the actual nonuniform
                        # deficit states generated by preceding stages.
                        assert b0.denominator == 1
                        assert blocks == [int(b0)] * p.k, (
                            d, t, i, j, role, blocks, b0
                        )
                        assert F(a) - F(up) == p.k * b0
        print(f"d={d}: stages={len(table)}, active rows="
              f"{sum(sum(1 for _ in rows) for step in table for rows in step.values())}")
    print(f"PASS: explicit U allocation and equal-child-block checks through d={max_depth}; "
          f"role instances={sum(total_nodes.values())}.")
    print("Finite scheduler verification only; this does not prove a sorting theorem.")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--depth", type=int, default=8)
    args = ap.parse_args()
    check(args.depth)


if __name__ == "__main__":
    main()
